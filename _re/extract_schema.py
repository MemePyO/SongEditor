"""Read-only ProPresenter 7 .pro schema extractor.

Extracts the protobuf schema from SongEditor's generated *_pb2.py modules and
cross-references it with real .pro files found on disk. Writes a markdown report
to _re/pro_format_report.md. No existing files are modified.

Run from the SongEditor repository root:
    python _re/extract_schema.py
"""

import glob
import importlib
import os
import sys
from collections import defaultdict

from google.protobuf import descriptor_pb2
from google.protobuf.descriptor import FieldDescriptor

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

REPORT = os.path.join(HERE, "pro_format_report.md")

PRO_DIRS = [
    ROOT,
    os.path.join(os.path.expanduser("~"), "Downloads"),
    os.path.join(
        os.environ.get("APPDATA", os.path.join(os.path.expanduser("~"), "AppData", "Roaming")),
        "RenewedVision",
        "ProPresenter",
        "LocalWorkspaces",
    ),
]

TYPE_MAP = {
    FieldDescriptor.TYPE_DOUBLE: "double",
    FieldDescriptor.TYPE_FLOAT: "float",
    FieldDescriptor.TYPE_INT64: "int64",
    FieldDescriptor.TYPE_UINT64: "uint64",
    FieldDescriptor.TYPE_INT32: "int32",
    FieldDescriptor.TYPE_FIXED64: "fixed64",
    FieldDescriptor.TYPE_FIXED32: "fixed32",
    FieldDescriptor.TYPE_BOOL: "bool",
    FieldDescriptor.TYPE_STRING: "string",
    FieldDescriptor.TYPE_GROUP: "group",
    FieldDescriptor.TYPE_MESSAGE: "message",
    FieldDescriptor.TYPE_BYTES: "bytes",
    FieldDescriptor.TYPE_UINT32: "uint32",
    FieldDescriptor.TYPE_ENUM: "enum",
    FieldDescriptor.TYPE_SFIXED32: "sfixed32",
    FieldDescriptor.TYPE_SFIXED64: "sfixed64",
    FieldDescriptor.TYPE_SINT32: "sint32",
    FieldDescriptor.TYPE_SINT64: "sint64",
}

def label_name(field):
    if field.is_repeated:
        return "repeated"
    if field.is_required:
        return "required"
    return "optional"


def field_type_name(field):
    tname = TYPE_MAP.get(field.type, str(field.type))
    if field.type == FieldDescriptor.TYPE_MESSAGE and field.message_type is not None:
        tname += f" <{field.message_type.full_name}>"
    elif field.type == FieldDescriptor.TYPE_ENUM and field.enum_type is not None:
        tname += f" <{field.enum_type.full_name}>"
    return tname


def walk_messages(descriptor, prefix, out, seen):
    if descriptor.full_name in seen:
        return
    seen.add(descriptor.full_name)
    for field in descriptor.fields:
        out.append((prefix + field.name, field))
    for nested in descriptor.nested_types:
        walk_messages(nested, prefix + nested.name + ".", out, seen)
    for enum in descriptor.enum_types:
        out.append((prefix + enum.name, ("ENUM", enum)))


def collect_paths(message, prefix, paths, depth=0):
    if depth > 8:
        return
    for field, value in message.ListFields():
        path = prefix + field.name
        paths.add(path)
        if field.type == FieldDescriptor.TYPE_MESSAGE:
            if field.is_repeated:
                for item in value:
                    collect_paths(item, path + "[].", paths, depth + 1)
            else:
                collect_paths(value, path + ".", paths, depth + 1)


def main():
    modules = []
    for path in sorted(glob.glob(os.path.join(ROOT, "*_pb2.py"))):
        name = os.path.splitext(os.path.basename(path))[0]
        try:
            modules.append((name, importlib.import_module(name)))
        except Exception as exc:  # noqa: BLE001
            print(f"[warn] could not import {name}: {exc}")

    file_descriptors = []
    seen_files = set()
    for name, mod in modules:
        fd = getattr(mod, "DESCRIPTOR", None)
        if fd is not None and fd.name not in seen_files:
            seen_files.add(fd.name)
            file_descriptors.append((name, fd))

    lines = []
    lines.append("# ProPresenter 7 .pro schema report")
    lines.append("")
    lines.append("Generated by `_re/extract_schema.py` (read-only analysis).")
    lines.append("")
    lines.append(f"- SongEditor modules imported: {len(modules)}")
    lines.append(f"- File descriptors: {len(file_descriptors)}")
    lines.append("")

    lines.append("## 1. Message catalog (from SongEditor *_pb2.py)")
    lines.append("")
    for name, fd in file_descriptors:
        entries = []
        seen = set()
        for msg in fd.message_types_by_name.values():
            walk_messages(msg, msg.name + ".", entries, seen)
        for enum in fd.enum_types_by_name.values():
            entries.append((enum.name, ("ENUM", enum)))
        lines.append(f"### File: `{name}`")
        lines.append("")
        if not entries:
            lines.append("(no messages/enums)")
            lines.append("")
            continue
        lines.append("| Name | Number | Label | Type |")
        lines.append("|---|---|---|---|")
        for field_name, field in entries:
            if isinstance(field, tuple) and field[0] == "ENUM":
                enum = field[1]
                vals = ", ".join(f"{v.name}={v.number}" for v in enum.values)
                lines.append(f"| {field_name} | - | enum | {vals} |")
            else:
                lines.append(
                    f"| {field_name} | {field.number} | "
                    f"{label_name(field)} | {field_type_name(field)} |"
                )
        lines.append("")

    # Sample files
    pro_files = []
    for d in PRO_DIRS:
        for p in glob.glob(os.path.join(d, "**", "*.pro"), recursive=True):
            pro_files.append(p)
    pro_files = sorted(set(pro_files))

    import presentation_pb2 as presentation_pb2

    top_usage = defaultdict(int)
    path_usage = defaultdict(int)
    app_versions = defaultdict(int)
    cue_counts = []
    parsed = 0
    failed = []
    for p in pro_files:
        try:
            with open(p, "rb") as f:
                pres = presentation_pb2.Presentation()
                pres.ParseFromString(f.read())
        except Exception as exc:  # noqa: BLE001
            failed.append((p, str(exc)))
            continue
        parsed += 1
        for field, _ in pres.ListFields():
            top_usage[field.name] += 1
        file_paths = set()
        collect_paths(pres, "", file_paths)
        for path in file_paths:
            path_usage[path] += 1
        ai = pres.application_info.application_version
        app_versions[(ai.major_version, ai.minor_version, ai.patch_version, ai.build)] += 1
        cue_counts.append((p, len(pres.cues), len(pres.arrangements), len(pres.cue_groups)))

    lines.append("## 2. Sample .pro files")
    lines.append("")
    lines.append(f"- Parsed successfully: {parsed}")
    lines.append(f"- Failed to parse: {len(failed)}")
    lines.append(f"- Total candidate files: {len(pro_files)}")
    lines.append("")

    lines.append("### 2.1 Top-level Presentation field usage (files containing the field)")
    lines.append("")
    lines.append("| Field | Files |")
    lines.append("|---|---|")
    for name, count in sorted(top_usage.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| {name} | {count} |")
    lines.append("")

    lines.append("### 2.2 application_version values seen")
    lines.append("")
    lines.append("| major | minor | patch | build | files |")
    lines.append("|---|---|---|---|---|")
    for (maj, mnr, pat, bld), count in sorted(app_versions.items(), key=lambda kv: -kv[1]):
        lines.append(f"| {maj} | {mnr} | {pat} | {bld} | {count} |")
    lines.append("")

    lines.append("### 2.3 Cue / arrangement / cue_group counts per file")
    lines.append("")
    lines.append("| File | cues | arrangements | cue_groups |")
    lines.append("|---|---|---|---|")
    for p, c, a, g in cue_counts:
        lines.append(f"| {p} | {c} | {a} | {g} |")
    lines.append("")

    lines.append("## 3. Populated field paths (all files combined)")
    lines.append("")
    lines.append("| Path | Files |")
    lines.append("|---|---|")
    for path, count in sorted(path_usage.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| {path} | {count} |")
    lines.append("")

    if failed:
        lines.append("## 4. Parse failures")
        lines.append("")
        for p, err in failed:
            lines.append(f"- {p}: {err}")
        lines.append("")

    with open(REPORT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"report written: {REPORT}")
    print(f"parsed {parsed} files, {len(pro_files)} candidates, {len(failed)} failures")


if __name__ == "__main__":
    main()
